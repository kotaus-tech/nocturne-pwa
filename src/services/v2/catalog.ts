//
// В отличие от универсальных тегов V1, каждая категория здесь имеет
// собственный смысл: пол и возраст — идентичность, сарказм — речь,
// соседи — контекст отношений, ревность — поведение в отношениях.
//
// У каждой опции стабильный `id` (внутренний ключ), `name` (для UI) и
// `hint` — семантическая инструкция, которую мы передаём модели вместо
// голого названия. Переименование `name` не ломает сохранённые данные.
// =============================================================

import type { V2Preset } from "./v2types";

export interface V2Option {
  id: string;
  name: string;
  /** Семантика для генератора: что именно эта опция означает в персонаже. */
  hint: string;
}

export interface V2Category {
  id: string;
  title: string;
  icon: string;
  /** Сколько опций можно выбрать одновременно (1 = одиночный выбор). */
  max: number;
  /** Показывать только в «Расширенных настройках». */
  advanced?: boolean;
  /** Короткое пояснение для UI. */
  note?: string;
  options: V2Option[];
}

