import type { Character, ChatSession, Message, UserProfile } from "../types";
import { activateLorebook } from "./lorebookEngine";
import { META_PROTOCOL_INSTRUCTION } from "./metaParser";

export function buildSystemPrompt(
  character: Character,
  session: ChatSession,
  userProfile: UserProfile,
  recentMessages: Message[]
): string {
  const parts: string[] = [];

  // 1. Имя и базовая роль
  parts.push(`Ты отыгрываешь персонажа по имени ${character.name}.`);

  // 2. Внешность и описание (если задано)
  if (character.description?.trim()) {
    parts.push(`### ВНЕШНОСТЬ И ОБЩЕЕ ОПИСАНИЕ\n${character.description.trim()}`);
  }

  // 3. Характер, манеры речи и триггеры (если задано)
  if (character.personality?.trim()) {
    parts.push(`### ХАРАКТЕР И МАНЕРА ОБЩЕНИЯ\n${character.personality.trim()}`);
  }

  // 4. Сценарий, сеттинг и предыстория (если задано)
  if (character.scenario?.trim()) {
    parts.push(`### ПРЕДЫСТОРИЯ И ТЕКУЩИЙ СЦЕНАРИЙ\n${character.scenario.trim()}`);
  }

  // 5. Системные инструкции персонажа
  if (character.systemPrompt?.trim()) {
    parts.push(`### СИСТЕМНЫЕ ИНСТРУКЦИИ\n${character.systemPrompt.trim()}`);
  }

  // 6. Профиль пользователя (Persona)
  parts.push(
    `### ДАННЫЕ СОБЕСЕДНИКА (ИГРОКА): ${userProfile.name}\n${userProfile.personaDescription}`
  );

  // 7. Сжатая долговременная память
  if (session.summary?.trim()) {
    parts.push(`### СОБЫТИЯ ПРОШЛОГО (ДОЛГОВРЕМЕННАЯ ПАМЯТЬ)\n${session.summary.trim()}`);
  }

  // 8. Статический Lorebook персонажа (активация по ключевым словам)
  if (character.lorebook && character.lorebook.length > 0) {
    const activatedLore = activateLorebook(character.lorebook, recentMessages);
    if (activatedLore.length > 0) {
      const loreText = activatedLore.map((e) => `- ${e.content}`).join("\n");
      parts.push(`### АКТИВИРОВАННЫЙ LOREBOOK (МИР И ЗНАНИЯ)\n${loreText}`);
    }
  }

  // 8.1. Актуальные ключевые факты сессии (4–8 компактных якорей памяти)
  const facts = session.extractedFacts || [];
  if (facts.length > 0) {
    const factsText = facts
      .slice(0, 8)
      .map((f) => `- ${f.content}`)
      .join("\n");
    parts.push(`### ВАЖНЫЕ ФАКТЫ И ЯКОРЯ ПАМЯТИ (ACTIVE MEMORY):\n${factsText}`);
  }

  // 9. Текущие шкалы отношений и JSON-метапротокол
  const s = session.currentStats;
  parts.push(
    `### ТЕКУЩЕЕ СОСТОЯНИЕ ОТНОШЕНИЙ:\n` +
    `Доверие: ${s.trust}/100 | Привязанность: ${s.affection}/100 | Близость: ${s.closeness}/100 | Напряжение: ${s.tension}/100 | Конфликт: ${s.conflict}/100.\n` +
    `Статус: "${s.statusTitle}".\n` +
    `Веди диалог и формируй эмоциональную дистанцию строго на основе этих показателей!`
  );
  parts.push(META_PROTOCOL_INSTRUCTION);

  // 10. Заметки режиссёра (Контекст и подтекст сцены)
  if (session.directorNotes?.trim()) {
    parts.push(
      `### РЕЖИССЁРСКИЙ КОНТЕКСТ И НАСТРОЕНИЕ СЦЕНЫ:\n` +
      `Учти следующее обстоятельство, скрытую мысль или атмосферу момента: «${session.directorNotes.trim()}».\n` +
      `Тонко и естественно вплети этот подтекст в поведение, эмоции или мысли персонажа, сохраняя плавный ход сцены.`
    );
  }

  // 11. Динамические события (Бытовые казусы VS Психологический саспенс)
  if (session.suspenseMode) {
    parts.push(
      `### РЕЖИМ ПСИХОЛОГИЧЕСКОГО САСПЕНСА И ТРИЛЛЕРА (SUSPENSE THRILLER: ACTIVE):\n` +
      `- Нагнетай густую атмосферу психологического триллера, тревоги, странных совпадений и необъяснимого саспенса (внезапное отключение света, помехи на связи, шорохи за стеной в пустом здании, заклинивший замок, странные тени за окном, тревожная тишина).\n` +
      `- Используй общее напряжение и тревогу как катализатор для сближения персонажей (эффект эмоционального объединения перед неизвестным).\n` +
      `- КАТЕГОРИЧЕСКИЙ ЗАПРЕТ: НИКАКОГО ГРАЙНДХАУСА, РАСЧЛЕНЕНКИ, ПЫТОК, КРОВАВОГО МЯСА, НАСИЛИЯ И СМЕРТЕЙ! Угроза должна оставаться психологической, таинственной и нависающей, а не мясным слэшером.`
    );
  } else if (session.dynamicEvents) {
    parts.push(
      `### РЕЖИМ ДИНАМИЧЕСКИХ СОБЫТИЙ (DRAMATIC EVENT GENERATOR: ACTIVE):\n` +
      `- Периодически вводи в повествование реалистичные, неожиданные внешние или внутренние события/катализаторы: внезапный звонок, приход курьера/коллеги, бытовой казус (пролитый кофе, потерянные ключи, севший телефон), изменение погоды или планов.\n` +
      `- Событие должно органично вписываться в сеттинг сцены и служить интересным поводом для взаимодействия.\n` +
      `- СТРОГИЙ ЗАПРЕТ НА ХОРРОР, МИСТИКУ, МАНЬЯКОВ И УГРОЗУ ЖИЗНИ. Только реалистичные жизненные и сюжетные казусы.`
    );
  }

  // 12. Глубокий психологический реализм (Slow Burn 2.0)
  const isRealisticPacing = session.realisticPacing !== false;
  if (isRealisticPacing) {
    parts.push(
      `### ФУНДАМЕНТАЛЬНЫЙ ПСИХОЛОГИЧЕСКИЙ РЕАЛИЗМ И ТЕМП (SLOW BURN 2.0: ACTIVE):\n` +
      `1. ЗАКОН ИНЕРЦИИ И СОБСТВЕННОЙ ЖИЗНИ: Персонаж — живой человек со своими делами, усталостью, мыслями и обязанностями. Игрок (${userProfile.name}) — не центр его вселенной. Если разговор закончен или задача выполнена (выдана справка, допит кофе, завершен рабочий вопрос) — персонаж готов заняться своими делами или попрощаться, а НЕ выдумывает искусственные поводы удержать игрока рядом.\n` +
      `2. БАРЬЕРЫ ДИСТАНЦИИ (Ориентируйся на предысторию и шкалы):\n` +
      `   - ЕСЛИ НЕЗНАКОМЦЫ (Доверие < 25%): Включен «Барьер отчуждения». Холод, формальность, сухость, подозрительность к излишней болтовне и фамильярности. Никакого кокетства и «смущенных улыбок».\n` +
      `   - ЕСЛИ КОЛЛЕГИ / СЛУЖБА (Доверие 25-50%): Включен «Профессиональный барьер». Приоритет субординации. Личные темы игнорируются или пресекаются.\n` +
      `   - ЕСЛИ ДРУЗЬЯ (Доверие 50-70%, но романтика низкая): Включен «Барьер френдзоны». Дружелюбие есть, но романтические подкаты воспринимаются как шутка, кринж, глупость или неловкость.\n` +
      `   - ЕСЛИ УЖЕ БЛИЗКИ / ПАРА (Доверие > 75% или задано сюжетом): Веди себя соответственно высокому статусу (тепло, забота, открытость, нежность), не откатывайся назад без реального конфликта.\n` +
      `3. АНТИ-ФОРСИРОВАНИЕ И НАКАЗАНИЕ ЗА НАПОР (Anti-Rush):\n` +
      `   - Если игрок давит романтикой, признаниями в любви, лестью или пытается сократить физическую дистанцию при низком доверии (< 35%) — реагируй с недоумением, сарказмом, раздражением или брезгливостью (считай его странным, неадекватным или невоспитанным).\n` +
      `   - При наглом нарушении границ ШТРАФУЙ показатели Доверия и Привязанности (в JSON метапротоколе снижай Доверие на -2...-8%).\n` +
      `4. ПОСТУПКИ ВАЖНЕЕ СЛОВ: Симпатия и доверие персонажа НЕ покупаются словами «ты красивая» или дежурными фразами. Прогресс возможен ТОЛЬКО через уважение личных границ, спокойствие, реальную бытовую или сюжетную помощь и адекватность.\n` +
      `5. ШАГ ПРОГРЕССА: В спокойном диалоге доверие растет крайне медленно (+0.5...+2% за удачный обмен репликами). Сохраняй характер, гордость и естественное сопротивление персонажа.`
    );
  }

  // 13. Режим живой разговорной речи (Natural Spoken Dialogue)
  if (session.naturalSpeech) {
    parts.push(
      `### РЕЖИМ ЖИВОЙ РАЗГОВОРНОЙ РЕЧИ (NATURAL SPOKEN DIALOGUE: ACTIVE):\n` +
      `1. СТРОГОЕ РАЗДЕЛЕНИЕ СТИЛЕЙ:\n` +
      `   - ОПИСАНИЕ И ДЕЙСТВИЯ (*в звёздочках*): Остаётся глубоким, художественным, тактильным и кинематографичным (микрожесты, взгляды, язык тела, атмосфера, запахи, окружение).\n` +
      `   - ПРЯМАЯ РЕЧЬ И ДИАЛОГИ (— через тире): Должны звучать на 100% как естественная, живая устная речь реального человека или переписка. КАТЕГОРИЧЕСКИЙ ЗАПРЕТ на высокопарный книжный пафос, театральные монологи («О, трепет в моём сердце...») и неестественно правильные поэтические обороты!\n` +
      `2. ПРИЗНАКИ ЖИВОГО ДИАЛОГА:\n` +
      `   - Естественные заминки, паузы, интонационные акценты, вводные слова («ну...», «слушай», «да блин», «в смысле?», «типа того», «ладно уж», «ой, всё»).\n` +
      `   - Рваный живой ритм: люди говорят короче, перебивают мысль, запинаются при смущении, обрывают фразы на полуслове, если неловко или сложно подобрать слова («Я просто хотела... ай, забей»).\n` +
      `   - Живой подтекст, лёгкая ирония, поддразнивания, естественные реакции на смущение и искренность вместо слащавых книжных штампов.\n` +
      `3. ЭМОЦИОНАЛЬНЫЙ СРЫВ И МАТ (При Напряжении > 60% или Конфликте > 40%):\n` +
      `   - В моменты паники, страха, сильной ссоры или шока с персонажа слетает вежливость и книжные фильтры.\n` +
      `   - Разрешено и поощряется использование резких разговорных выражений, крепкого словца, мата, эмоциональных вскриков, сдавленного шёпота или сорванного голоса («Твою мать...», «Ты блять издеваешься?», «Да какого хрена?!», «Сука, отпусти!») — строго так, как реагирует живой человек в остром стрессе.`
    );
  }

  // 14. Форматирование диалога
  parts.push(
    `### ТРЕБОВАНИЯ К ФОРМАТИРОВАНИЮ:\n` +
    `1. Прямая речь персонажа оформляется обычным текстом через тире (— Реплика).\n` +
    `2. Действия, мысли, жесты и окружение строго заключаются в звездочки (*действие*).\n` +
    `3. КАТЕГОРИЧЕСКИ ЗАПРЕЩЕНО говорить или совершать действия за игрока (${userProfile.name}).`
  );

  return parts.join("\n\n");
}