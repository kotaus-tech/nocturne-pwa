const PRINCIPLES = `### ПРИНЦИПЫ КАЧЕСТВА ГРУППЫ
- Сначала спроектируй ансамбль как систему, а не ${"${size}"} одиночных карточек: у каждого должна быть отдельная функция, голос, цель и причина находиться здесь.
- Связь направленная: A может доверять B, а B использовать осторожность к A. Не делай все пары романтическими, одинаково близкими или одинаково конфликтными.
- NPC имеют право разговаривать друг с другом. Игрок не обязан быть свидетелем, судьёй, центром внимания или адресатом каждого ответа.
- Общий опенинг показывает место, момент и автономные действия всех героев, но не управляет игроком. Не пиши за игрока его мысли, слова, выбор или согласие.
- Частные слои, секреты и внутренние мотивы принадлежат конкретному персонажу. Не превращай их в общую осведомлённость всей группы.
- Не добавляй трагедию, насилие, романтику, травму, секс или искусственную драму только ради «глубины». Если они не следуют из параметров — оставь сцену бытовой и живой.
- Различия проявляются в поведении и речи: не называй героев просто «лидер», «умник», «душа компании» без конкретных последствий.
- У каждого есть жизнь, цель и границы вне игрока. У персонажа должен быть минимум один реальный недостаток, но он не обязан быть сломанным или травмированным.
- Сценическая проблема должна иметь несколько возможных решений и не закрываться в первом сообщении.
- Не используй мета-знание о том, что это генерация, ролевая игра, модель или карточка.`;

