export type RoleplayTurnMode = "normal" | "initiative" | "continue";

/**
 * Скрытая инструкция, добавляемая только к ручному продолжению сцены.
 * Это управляющий сигнал интерфейса, а не реплика игрока: модель должна
 * продолжить текущий момент, не превращая нажатие кнопки в «молчание» игрока.
 */
export function buildRoleplayTurnDirective(
  mode: RoleplayTurnMode,
  userName: string,
  speakerName: string
): string | null {
  if (mode === "continue") {
    return `[Продолжение текущей сцены. Это техническая команда интерфейса, а не новая реплика или действие со стороны ${userName}. Продолжи происходящее непосредственно с последнего момента от лица ${speakerName}, в новом сообщении, без повтора и пересказа уже выданного текста. Последняя реплика могла оборваться из-за длины сообщения, но не начинай сцену заново. Не меняй роль ${userName} и не добавляй за него реплики, мысли, решения или действия. Верни только следующую часть своей ролевой реплики или действия.]`;
  }

  if (mode === "initiative") {
    return `[${userName} молчит или выжидает. ${speakerName}, прояви собственную инициативу: продолжи мысль, соверши физическое действие, измени положение, начни новую реплику или нарушь паузу. НЕ говори и НЕ действуй за ${userName}!]`;
  }

  return null;
}
