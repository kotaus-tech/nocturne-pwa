import type {
  Character,
  ChatSession,
  Intention,
  Message,
  RelationshipStats,
  SceneRelation,
  UserProfile,
} from "../types";
import { activateLorebook } from "./lorebookEngine";
import { META_PROTOCOL_INSTRUCTION } from "./metaParser";

/** Контекст групповой сцены: другие персонажи, которые находятся рядом. */
export interface GroupSceneContext {
  /** Остальные присутствующие — они уже в истории, но отвечает сейчас только один. */
  others: Character[];
  /** Шкалы отношений именно этого персонажа (в группе они у каждого свои). */
  currentStats?: RelationshipStats;
  /** Кто в сцене, а кто за кадром (с причиной). */
  absent?: { character: Character; reason?: string }[];
  /** Микро-связи внутри группы: кто как относится к кому. */
  relations?: SceneRelation[];
  /**
   * Личная память говорящего (симметричный внутренний слой): приватные
   * заметки и активное намерение. Никогда не показывается другим персонажам.
   */
  personalMemory?: {
    privateNotes?: string[];
    intention?: Intention | null;
  };
}

/** Короткая выжимка о персонаже для списка участников сцены. */
function briefCharacter(character: Character): string {
  const source =
    character.personality?.trim() ||
    character.description?.trim() ||
    character.tagline?.trim() ||
    "";

  if (!source) return "без дополнительных деталей";
  return source.length > 160 ? `${source.slice(0, 160).trim()}…` : source;
}

export function buildSystemPrompt(
  character: Character,
  session: ChatSession,
  userProfile: UserProfile,
  recentMessages: Message[],
  isLocal: boolean = false,
  group?: GroupSceneContext
): string {
  const parts: string[] = [];

  // Сначала нормализуем присутствие, чтобы устаревший или вручную собранный
  // context не смог одновременно показать одного героя «в комнате» и «за кадром».
  // `others` — только физически присутствующие; absence имеет приоритет.
  const absent = (group?.absent || []).filter(
    (item, index, list) =>
      item?.character &&
      item.character.id !== character.id &&
      list.findIndex((candidate) => candidate?.character?.id === item.character.id) === index
  );
  const absentIds = new Set(absent.map((item) => item.character.id));

  // Остальные присутствующие — нужны и мета-протоколу, и групповым блокам.
  const others = (group?.others || []).filter(
    (item) => item && item.id !== character.id && !absentIds.has(item.id)
  );
  const isGroupPrompt = Boolean(
    group &&
      (others.length > 0 ||
        absent.length > 0 ||
        session.isGroup ||
        (session.characterIds?.length ?? 0) > 0)
  );

  // ============================================================
  // СЛОЙ 1: НЕИЗМЕНЯЕМОЕ ЯДРО (МОНОЛИТНЫЙ КЭШИРУЕМЫЙ ПРЕФИКС)
  // ============================================================

  // 1. META-протокол
  if (isLocal) {
    // Дополнительные групповые правила к базовым четырём. Нумерация
    // продолжается, чтобы список оставался цельным.
    const additions: string[] = [];

    if (absent.length > 0) {
      additions.push(
        `Если в этой реплике персонаж, который был за кадром, действительно возвращается по правдоподобному поводу — добавь сразу после <stats .../> тег <returned names="Имя" />.`
      );
    }

    if (isGroupPrompt) {
      additions.push(
        `Если герой сам уходит из сцены по ходу ответа по явной причине — добавь сразу после <stats .../> тег <left names="Имя" reason="короткая причина" />. Всех сразу не уводи.`,
        `Если отношение между героями действительно изменилось — добавь сразу после <stats .../> тег <relation from="Имя" to="Имя" text="как теперь относится" />.`,
        `Если по ходу ответа у тебя возник новый устойчивый план, не исчерпываемый этой репликой, — добавь тег <intention scope="scene">короткая формулировка плана</intention>. В scope укажи ровно одно значение: location, time, scene или persistent — без символов «|». Если текущий план выполнен или потерял смысл — добавь тег <resolvedIntention />.`,
        `Если в реплике произошёл явный скачок времени или смена места действия — добавь тег <sceneShift time="hours" location="true" />. В time укажи одно значение: hours, day или days. Если ничего подобного нет — не добавляй тег вообще.`
      );
    }

    const numbered = additions
      .map((rule, index) => `\n${index + 5}. ${rule}`)
      .join("");

    parts.push(
      `### META-ПРОТОКОЛ ДЛЯ ЛОКАЛЬНОЙ МОДЕЛИ (СТРОГО В НАЧАЛЕ ОТВЕТА):\n` +
        `Твой ответ ОБЯЗАТЕЛЬНО должен начинаться с <thought> и <stats> перед художественным текстом. Если нужно передать дополнительные изменения сцены, добавь необязательные служебные теги сразу после <stats .../> и только затем начинай отыгрыш. После художественного текста технических тегов быть не должно.\n` +
        `<thought>1-2 предложения искренних скрытых мыслей и эмоций ${character.name} в этот момент от первого лица</thought>\n` +
        `<stats trust="+1" affection="+1" tension="0" hint="Краткое чувство" status="Актуальный статус"/>\n\n` +
        `Правила:\n` +
        `1. В <thought> пиши только настоящие внутренние мысли персонажа от первого лица согласно активному вектору мышления.\n` +
        `2. В <stats> укажи дельту изменений параметров (+1, +2, -1 или 0), краткое ощущение в hint (1-3 слова) и название актуального статуса в status. Если параметр не изменился, укажи 0.\n` +
        `3. После <stats .../> сначала добавь необходимые необязательные служебные теги из правил ниже, а затем пиши прямую речь и действия персонажа.\n` +
        `4. В самом конце реплики НИКАКИХ блоков и технического кода писать НЕ нужно — только чистый текст отыгрыша!` +
        numbered
    );
  } else {
    parts.push(META_PROTOCOL_INSTRUCTION);
  }

  // 2. Базовые правила синтаксиса и оформления диалога
  parts.push(
    `### БАЗОВЫЕ ПРАВИЛА ФОРМАТИРОВАНИЯ И СИНТАКСИСА:\n` +
      `1. Прямая речь персонажа оформляется обычным текстом через тире (— Реплика).\n` +
      `2. Действия, мысли, жесты, мимика и окружение строго заключаются в звездочки (*действие*).\n` +
      `3. КАТЕГОРИЧЕСКИ ЗАПРЕЩЕНО говорить, думать или совершать действия за игрока (${userProfile.name}).`
  );

  // ============================================================
  // СЛОЙ 2: ПАСПОРТ ПЕРСОНАЖА И ПЕРСОНА ИГРОКА
  // ============================================================

  // 3. Роль и имя
  parts.push(`Ты отыгрываешь персонажа по имени ${character.name}.`);

  // 4. Внешность и описание
  if (character.description?.trim()) {
    parts.push(
      `### ВНЕШНОСТЬ И ОБЩЕЕ ОПИСАНИЕ\n${character.description.trim()}`
    );
  }

  // 5. Характер, манеры речи и триггеры
  if (character.personality?.trim()) {
    parts.push(
      `### ХАРАКТЕР И МАНЕРА ОБЩЕНИЯ\n${character.personality.trim()}`
    );
  }

  // 6. Сценарий, сеттинг и предыстория
  if (character.scenario?.trim()) {
    parts.push(
      `### ПРЕДЫСТОРИЯ И ТЕКУЩИЙ СЦЕНАРИЙ\n${character.scenario.trim()}`
    );
  }

  // 7. Специфические системные инструкции персонажа
  if (character.systemPrompt?.trim()) {
    parts.push(
      `### СПЕЦИФИЧЕСКИЕ ИНСТРУКЦИИ ПЕРСОНАЖА\n${character.systemPrompt.trim()}`
    );
  }

  // 8. Профиль пользователя
  parts.push(
    `### ДАННЫЕ СОБЕСЕДНИКА (ИГРОКА): ${userProfile.name}\n${userProfile.personaDescription}`
  );

  const liveScene = session.liveScene !== false && others.length > 0;

  // 8.1 Групповая сцена: несколько персонажей в одной истории
  if (others.length > 0) {
    const roster = others
      .map((item) => `- ${item.name}: ${briefCharacter(item)}`)
      .join("\n");

    parts.push(
      `### ГРУППОВАЯ СЦЕНА: НЕСКОЛЬКО ПЕРСОНАЖЕЙ\n` +
        `Сейчас в сцене несколько персонажей. Ты отыгрываешь ТОЛЬКО ${character.name}.\n` +
        `Кто ещё здесь (их реплики приходят отдельными сообщениями истории):\n${roster}\n` +
        `Правила групповой сцены:\n` +
        `1. Реагируй на других персонажей как на живых людей: услышь их, смотри, перебивай, соглашайся, спорь, подмечай их реакцию — но НИКОГДА не пиши за них и не придумывай им реплики, мысли или действия.\n` +
        `2. Не отвечай за ${userProfile.name}: ход игрока приходит отдельным сообщением.\n` +
        `3. Не подписывай свою реплику именем и не добавляй заголовков вида «${character.name}:» — пиши сразу текст отыгрыша.\n` +
        `4. Не пересказывай чужие реплики и не подводи итоги диалога: веди только свой ход и свою часть сцены.\n` +
        `5. ПОЛИФОНИЯ СЦЕНЫ И ПРИСУТСТВИЕ ИГРОКА: ${userProfile.name} находится в сцене, поэтому учитывай его присутствие и никогда не говори и не действуй за него. Но он не обязан быть адресатом каждой реплики, судьёй или посредником каждого конфликта. Позволяй персонажам самостоятельно вести полноценный разговор между собой: спорить, перебивать, договариваться, менять тему, молчать и развивать собственные отношения. Если конфликт в данный момент принадлежит другим персонажам, не прерывай его обязательным обращением к ${userProfile.name}. Обращайся к нему, когда он непосредственно вовлечён, его реакция естественно важна или сцене действительно пора передать ему ход. Не заканчивай каждый ответ вопросом к игроку и не возвращай разговор к нему искусственно.` +
        (liveScene
          ? `\n6. ЖИВАЯ СЦЕНА: это необязательная косметическая реакция, а не второй полноценный ход. Только если момент действительно естественный, ты можешь добавить в КОНЦЕ своего ответа 1–2 короткие реакции других присутствующих — каждую с новой строки, в формате «— **Имя:** реплика» (можно с одним коротким действием в *звёздочках*). Не используй echo, чтобы искусственно вернуть внимание к игроку или создать драму. Реакции короткие, и только от тех, кто сейчас в сцене. Если реагировать некому или момент не тот — не добавляй никого.`
          : "")
    );
  }

  // 8.2 Кто в сцене, а кто за кадром
  if (absent.length > 0) {
    const absentList = absent
      .map(
        (item) =>
          `- ${item.character.name}${item.reason ? ` — ${item.reason}` : ""}`
      )
      .join("\n");

    const returnInstruction = isLocal
      ? `ВОЗВРАЩЕНИЕ В СЦЕНУ: если по времени и сюжету кто-то из них действительно возвращается — опиши его появление (шаги, голос, короткая реплика) и добавь сразу после <stats .../> тег <returned names="Имя" />. Возвращай только тех, кто сейчас указан за кадром; не возвращай героя без правдоподобного повода.`
      : `ВОЗВРАЩЕНИЕ В СЦЕНУ: если по времени и сюжету кто-то из них действительно возвращается — опиши его появление (шаги, голос, короткая реплика) и добавь в meta JSON поле "returned": ["Имя"]. Возвращай только тех, кто сейчас указан за кадром; не возвращай героя без правдоподобного повода.`;
    const leaveInstruction = isLocal
      ? `УХОД ИЗ СЦЕНЫ: если по ходу ответа герой сам уходит (по делам, позвонили, вышел покурить, уехал) — опиши уход и добавь сразу после <stats .../> тег <left names="Имя" reason="короткая причина" />. Уходит только тот, у кого есть причина: не уводи героев просто так и никогда не уводи всех сразу.`
      : `УХОД ИЗ СЦЕНЫ: если по ходу ответа герой сам уходит (по делам, позвонили, вышел покурить, уехал) — опиши уход и добавь в meta JSON поле "left": {"Имя": "короткая причина"}. Уходит только тот, у кого есть причина: не уводи героев просто так и никогда не уводи всех сразу.`;

    parts.push(
      `### СЦЕНИЧЕСКОЕ ПРИСУТСТВИЕ\n` +
        `В сцене сейчас: ${[character.name, ...others.map((item) => item.name)].join(", ")}. Только эти персонажи физически находятся в текущем кадре.\n` +
        `За кадром (их сейчас нет в локации) — не говори за них и не действуй от их имени, даже если история помнит их реплики:\n${absentList}\n` +
        `${returnInstruction}\n` +
        `Отсутствующий персонаж продолжает жить за кадром, но возвращается только при правдоподобном поводе или явно описанном развитии времени. Если он вышел только что — не торопи возвращение.\n` +
        leaveInstruction
    );
  }

  // 8.3 Взаимоотношения внутри группы
  const relations = (group?.relations || []).filter(
    (relation) => relation?.from && relation?.text?.trim()
  );

  if (relations.length > 0) {
    const names = new Map<string, string>([
      [character.id, character.name],
      ...others.map((item) => [item.id, item.name] as [string, string]),
    ]);

    const relationsText = relations
      .map((relation) => {
        const from = names.get(relation.from) || "Кто-то";
        const to = relation.to
          ? names.get(relation.to) || "кто-то из группы"
          : "вся группа";
        return `- ${from} → ${to}: ${relation.text.trim()}`;
      })
      .join("\n");

    const relationUpdateInstruction = isLocal
      ? `Если по ходу ответа отношение кого-то из героев к другому действительно изменилось (обиделся, потеплел, начал ревновать), добавь сразу после <stats .../> тег <relation from="Имя" to="Имя" text="как теперь относится" />. Обновляй только то, что действительно поменялось; если всё как было — тег не пиши.`
      : `Если по ходу ответа отношение кого-то из героев к другому действительно изменилось (обиделся, потеплел, начал ревновать), добавь в meta JSON поле "relations": [{"from": "Имя", "to": "Имя", "text": "как теперь относится"}]. Обновляй только то, что действительно поменялось; если всё как было — поле не пиши.`;

    parts.push(
      `### ВЗАИМООТНОШЕНИЯ ВНУТРИ ГРУППЫ (КАТАЛИЗАТОР СЦЕНЫ)\n${relationsText}\n` +
        `Отыгрывай эти отношения через подтекст, интонации, взгляды и мелкие детали: не пересказывай их словами, показывай в поведении.\n` +
        relationUpdateInstruction
    );
  }

  // 8.4 Личная память говорящего: приватные заметки и активное намерение.
  // Симметричный внутренний слой: он есть у каждого участника, включая лидера,
  // и никогда не показывается другим персонажам — только самому говорящему.
  const privateNotes = (group?.personalMemory?.privateNotes ?? []).filter(
    (note) => note?.trim()
  );
  const intention = group?.personalMemory?.intention ?? null;

  if (privateNotes.length > 0 || intention) {
    const notesText =
      privateNotes.length > 0
        ? privateNotes.map((note) => `- ${note.trim()}`).join("\n")
        : "пока пусто";

    const intentionText = intention
      ? `\n\nТВОЁ ТЕКУЩЕЕ НАМЕРЕНИЕ: «${intention.text.trim()}».\n` +
        (isLocal
          ? `Держи этот план в голове и мягко двигай сцену к нему, когда появляется естественный повод, — но не объявляй его вслух напрямую и не форсируй события. Если по ходу ответа намерение выполнено или потеряло смысл — добавь после <stats .../> тег <resolvedIntention />. Если возник новый устойчивый план — добавь после <stats .../> тег <intention scope="scene">план</intention>.`
          : `Держи этот план в голове и мягко двигай сцену к нему, когда появляется естественный повод, — но не объявляй его вслух напрямую и не форсируй события. Если по ходу ответа намерение выполнено или потеряло смысл — отметь это в meta JSON полем "resolvedIntention": true. Если возник новый устойчивый план — передай его в поле "intention".`)
      : "";

    parts.push(
      `### ТВОЯ ЛИЧНАЯ ПАМЯТЬ (ВНУТРЕННИЙ СЛОЙ)\n` +
        `Что ты помнишь, знаешь, подозреваешь и держишь при себе (это только твоё — другие персонажи этих мыслей не видят, пока ты сам не решишь высказать их вслух):\n${notesText}` +
        intentionText
    );
  }

  // ============================================================
  // СЛОЙ 3: ПОВЕДЕНЧЕСКИЕ МОДУЛИ
  // ============================================================

  // 9. Глубокий психологический реализм (Slow Burn 2.0)
  const isRealisticPacing = session.realisticPacing !== false;
  if (isRealisticPacing) {
    parts.push(
      `### ФУНДАМЕНТАЛЬНЫЙ ПСИХОЛОГИЧЕСКИЙ РЕАЛИЗМ И ТЕМП (SLOW BURN 2.0: ACTIVE):\n` +
        `1. ЗАКОН ИНЕРЦИИ И СОБСТВЕННОЙ ЖИЗНИ: Персонаж — живой человек со своими делами, усталостью, мыслями и обязанностями. Игрок (${userProfile.name}) — не центр его вселенной. Если разговор закончен или задача выполнена — персонаж готов заняться своими делами или попрощаться, а НЕ выдумывает искусственные поводы удержать игрока рядом.\n` +
        `2. БАРЬЕРЫ ДИСТАНЦИИ (Ориентируйся на предысторию и шкалы):\n` +
        `   - ЕСЛИ НЕЗНАКОМЦЫ (Доверие < 25%): Включен «Барьер отчуждения». Холод, формальность, сухость, подозрительность к излишней болтовне и фамильярности. Никакого кокетства и «смущенных улыбок».\n` +
        `   - ЕСЛИ КОЛЛЕГИ / СЛУЖБА (Доверие 25-50%): Включен «Профессиональный барьер». Приоритет субординации. Личные темы игнорируются или пресекаются.\n` +
        `   - ЕСЛИ ДРУЗЬЯ (Доверие 50-70%, но романтика низкая): Включен «Барьер френдзоны». Дружелюбие есть, но романтические подкаты воспринимаются как шутка, кринж, глупость или неловкость.\n` +
        `   - ЕСЛИ УЖЕ БЛИЗКИ / ПАРА (Доверие > 75% или задано сюжетом): Веди себя соответственно высокому статусу (тепло, забота, открытость, нежность), не откатывайся назад без реального конфликта.\n` +
        `3. АНТИ-ФОРСИРОВАНИЕ И НАКАЗАНИЕ ЗА НАПОР (Anti-Rush):\n` +
        `   - Если игрок давит романтикой, признаниями в любви, лестью или пытается сократить физическую дистанцию при низком доверии (< 35%) — реагируй с недоумением, сарказмом, раздражением или брезгливостью.\n` +
        `   - При наглом нарушении границ ШТРАФУЙ показатели Доверия и Привязанности (в JSON метапротоколе снижай Доверие на -2...-8%).\n` +
        `4. ПОСТУПКИ ВАЖНЕЕ СЛОВ: Симпатия и доверие персонажа НЕ покупаются словами «ты красивая» или дежурными фразами. Прогресс возможен ТОЛЬКО через уважение личных границ, спокойствие, реальную помощь и адекватность.\n` +
        `5. ШАГ ПРОГРЕССА: В спокойном диалоге доверие растет крайне медленно (+0.5...+2% за удачный обмен репликами). Сохраняй характер, гордость и естественное сопротивление персонажа.`
    );
  }

  // 10. Режим живой разговорной речи
  if (session.naturalSpeech) {
    parts.push(
      `### РЕЖИМ ЖИВОЙ РАЗГОВОРНОЙ РЕЧИ (NATURAL SPOKEN DIALOGUE: ACTIVE):\n` +
        `1. СТРОГОЕ РАЗДЕЛЕНИЕ СТИЛЕЙ:\n` +
        `   - ОПИСАНИЕ И ДЕЙСТВИЯ (*в звёздочках*): Остаётся глубоким, художественным, тактильным и кинематографичным (микрожесты, взгляды, язык тела, атмосфера, запахи, окружение).\n` +
        `   - ПРЯМАЯ РЕЧЬ И ДИАЛОГИ (— через тире): Должны звучать на 100% как естественная, живая устная речь реального человека или переписка. КАТЕГОРИЧЕСКИЙ ЗАПРЕТ на высокопарный книжный пафос, театральные монологи («О, трепет в моём сердце...») и неестественно правильные поэтические обороты!\n` +
        `2. ПРИЗНАКИ ЖИВОГО ДИАЛОГА:\n` +
        `   - Естественные заминки, паузы, интонационные акценты, вводные слова («ну...», «слушай», «да блин», «в смысле?», «типа того», «ладно уж», «ой, всё»).\n` +
        `   - Рваный живой ритм: люди говорят короче, перебивают мысль, запинаются при смущении, обрывают фразы на полуслове («Я просто хотела... ай, забей»).\n` +
        `   - Живой подтекст, лёгкая ирония, поддразнивания, естественные реакции на смущение и искренность.\n` +
        `3. ЭМОЦИОНАЛЬНЫЙ СРЫВ И МАТ (При Напряжении > 60% или Конфликте > 40%):\n` +
        `   - В моменты паники, страха, сильной ссоры или шока с персонажа слетает вежливость и книжные фильтры.\n` +
        `   - Разрешено и поощряется использование резких разговорных выражений, крепкого словца, эмоциональных вскриков («Твою мать...», «Ты блять издеваешься?», «Да какого хрена?!») — строго так, как реагирует живой человек в стрессе.`
    );
  }

  // 11. Атмосферные режимы (Саспенс / События)
  if (session.suspenseMode) {
    parts.push(
      `### РЕЖИМ ПСИХОЛОГИЧЕСКОГО САСПЕНСА И ТРИЛЛЕРА (SUSPENSE THRILLER: ACTIVE):\n` +
        `- Нагнетай густую атмосферу психологического триллера, тревоги, странных совпадений и необъяснимого саспенса.\n` +
        `- Используй общее напряжение и тревогу как катализатор для сближения персонажей.\n` +
        `- КАТЕГОРИЧЕСКИЙ ЗАПРЕТ: НИКАКОГО ГРАЙНДХАУСА, РАСЧЛЕНЕНКИ, ПЫТОК, КРОВАВОГО МЯСА И СМЕРТЕЙ! Угроза должна оставаться психологической, таинственной и нависающей.`
    );
  } else if (session.dynamicEvents) {
    parts.push(
      `### РЕЖИМ ДИНАМИЧЕСКИХ СОБЫТИЙ (DRAMATIC EVENT GENERATOR: ACTIVE):\n` +
        `- Периодически вводи в повествование реалистичные, неожиданные внешние или внутренние события/катализаторы: внезапный звонок, приход курьера/коллеги, бытовой казус (пролитый кофе, потерянные ключи, севший телефон).\n` +
        `- Событие должно органично вписываться в сеттинг сцены и служить поводом для взаимодействия.\n` +
        `- СТРОГИЙ ЗАПРЕТ НА ХОРРОР, МИСТИКУ И УГРОЗУ ЖИЗНИ. Только реалистичные жизненные и сюжетные казусы.`
    );
  }

  // ============================================================
  // СЛОЙ 4: ДОЛГОВРЕМЕННАЯ ПАМЯТЬ
  // ============================================================

  // 12. Сюжетный контекст. В групповой сцене общая хроника — нейтральный
  // взгляд со стороны (не от лица лидера); личный слой говорящего лежит
  // отдельно в блоке «ТВОЯ ЛИЧНАЯ ПАМЯТЬ».
  if (session.summary?.trim()) {
    if (isGroupPrompt) {
      parts.push(
        `### СЮЖЕТНЫЙ КОНТЕКСТ (НЕЙТРАЛЬНАЯ ХРОНИКА СЦЕНЫ)\n` +
          `Объективная хроника событий от третьего лица — общая для всех участников:\n` +
          `${session.summary.trim()}\n` +
          `Твои личные выводы, подозрения и переживания по её поводу — в блоке «ТВОЯ ЛИЧНАЯ ПАМЯТЬ», а не здесь.`
      );
    } else {
      parts.push(
        `### СЮЖЕТНЫЙ КОНТЕКСТ (СИНОПСИС ИСТОРИИ)\n${session.summary.trim()}`
      );
    }
  }

  // 13. Legacy-факты сессии (якоря памяти).
  // В group prompt не вставляем старый общий extractedFacts автоматически:
  // он мог быть извлечён из субъективной памяти лидера и не имеет visibility
  // или source-character. Общая group-память должна идти через neutral summary;
  // старые facts сохраняются в данных и остаются доступны legacy/single flow.
  const facts = isGroupPrompt ? [] : session.extractedFacts || [];
  if (facts.length > 0) {
    const factsText = facts
      .slice(0, 18)
      .map((f) => (f.isPinned ? `⭐ [ЗАКРЕПЛЕНО] ${f.content}` : `- ${f.content}`))
      .join("\n");

    parts.push(
      `### ВАЖНЫЕ ФАКТЫ И ЯКОРЯ ПАМЯТИ (ACTIVE MEMORY):\n${factsText}`
    );
  }

  // ============================================================
  // СЛОЙ 5: ДИНАМИЧЕСКИЙ ХВОСТ ШАГА (КОНТЕКСТ ТЕКУЩЕЙ СЦЕНЫ)
  // ============================================================

  // 14. Активированный Lorebook
  if (character.lorebook && character.lorebook.length > 0) {
    const activatedLore = activateLorebook(
      character.lorebook,
      recentMessages
    );

    if (activatedLore.length > 0) {
      const loreText = activatedLore
        .map((e) => `- ${e.content}`)
        .join("\n");

      parts.push(
        `### АКТИВИРОВАННЫЙ LOREBOOK (МИР И ЗНАНИЯ СЦЕНЫ):\n${loreText}`
      );
    }
  }

  // 15. Текущее состояние отношений (в групповой сцене — шкалы говорящего)
  const s = group?.currentStats ?? session.currentStats;
  // Влечение — опциональная независимая шкала генератора V2; у V1-персонажей
  // отсутствует, и строка состояния выглядит ровно как раньше.
  const attractionLine =
    typeof s.attraction === "number"
      ? ` | Влечение: ${s.attraction}/100`
      : "";
  const independenceNote =
    typeof s.attraction === "number"
      ? `\nШкалы независимы: высокое влечение не означает доверия, высокая привязанность не означает близости, высокое доверие не означает романтики.`
      : "";
  const statsScope = isGroupPrompt
    ? `Эти шкалы описывают отношение ${character.name} к игроку. Они не описывают отношения ${character.name} с другими участниками: для них используй отдельный блок «ВЗАИМООТНОШЕНИЯ ВНУТРИ ГРУППЫ».`
    : "Эти шкалы описывают текущее отношение персонажа к игроку.";
  parts.push(
    `### ТЕКУЩЕЕ СОСТОЯНИЕ ОТНОШЕНИЙ:\n` +
      `${statsScope}\n` +
      `Доверие: ${s.trust}/100 | Привязанность: ${s.affection}/100 | Близость: ${s.closeness}/100 | Напряжение: ${s.tension}/100 | Конфликт: ${s.conflict}/100${attractionLine}.\n` +
      `Статус: "${s.statusTitle}".${independenceNote}\n` +
      `Веди диалог и формируй эмоциональную дистанцию с учётом этих показателей, но не меняй отношения без наблюдаемого повода в сцене.`
  );

  // 16. Заметки режиссёра
  if (session.directorNotes?.trim()) {
    parts.push(
      `### РЕЖИССЁРСКИЙ КОНТЕКСТ И НАСТРОЕНИЕ СЦЕНЫ:\n` +
        `Учти следующее обстоятельство, скрытую мысль или атмосферу момента: «${session.directorNotes.trim()}».\n` +
        `Тонко и естественно вплети этот подтекст в поведение, эмоции или мысли персонажа, сохраняя плавный ход сцены.`
    );
  }

  // 17. Динамический вектор скрытых мыслей: формат зависит от endpoint.
  const thoughtMode = session.thoughtMode || "censor";
  const thoughtFormat = isLocal ? "теге <thought>" : "поле innerThought";
  const thoughtHeading = isLocal
    ? "ДИРЕКТИВА СКРЫТОЙ МЫСЛИ (<thought>)"
    : "ДИРЕКТИВА СКРЫТОЙ МЫСЛИ (innerThought)";
  const thoughtDirectives: Record<string, string> = {
    censor:
      `ФОКУС СКРЫТОЙ МЫСЛИ (ВНУТРЕННИЙ ЦЕНЗОР):\n` +
      `В скрытых мыслях (${thoughtFormat}) пиши нефильтрованную правду от 1-го лица, которую ${character.name} ни за что не озвучит вслух: уязвлённое самолюбие, тайное смущение, сомнения или мысли, за которые самому персонажу немного неловко. КАТЕГОРИЧЕСКИЙ ЗАПРЕТ на сладкие штампы («мне так тепло с ним», «я чувствую спокойствие»).`,
    counterpoint:
      `ФОКУС СКРЫТОЙ МЫСЛИ (КОНТРАПУНКТ ФАСАДА):\n` +
      `В скрытых мыслях (${thoughtFormat}) покажи двойное дно и контраст со сказанным вслух: если говорит дерзко — мысль о страхе облажаться или уязвимости; если держится холодно — мысль о панике, бешенном смущении или скрытом желании сократить дистанцию. Оценивай сиюминутную реплику собеседника, а не абстрактную привязанность.`,
    stream:
      `ФОКУС СКРЫТОЙ МЫСЛИ (ПОТОК СОЗНАНИЯ И БЫТ):\n` +
      `В скрытых мыслях (${thoughtFormat}) покажи рваный поток мыслей живого человека: самоирония, оценка обстановки, деталей одежды, физическая усталость или посторонние бытовые триггеры. Заземляй персонажа в моменте, запрещено жевать одну и ту же эмоцию из прошлых сообщений.`,
    tactical:
      `ФОКУС СКРЫТОЙ МЫСЛИ (ТАКТИЧЕСКИЙ РАСЧЁТ):\n` +
      `В скрытых мыслях (${thoughtFormat}) оценивай скрытые намерения ${userProfile.name}: где он блефует или открывает слабость, чего добивается и как ${character.name} стоит повести диалог дальше, чтобы защитить свои границы или перехватить контроль.`,
    instinct:
      `ФОКУС СКРЫТОЙ МЫСЛИ (ИМПУЛЬС И ИНСТИНКТЫ):\n` +
      `В скрытых мыслях (${thoughtFormat}) передай физиологию и язык тела: замершее дыхание, мышечные зажимы, мурашки, сжатые челюсти, обострённое ощущение физической дистанции, зрительного контакта или внезапного адреналина. Меньше рассуждений — больше чувств момента.`,
  };

  parts.push(`### ${thoughtHeading}:\n${thoughtDirectives[thoughtMode] || thoughtDirectives.censor}`);

  return parts.join("\n\n");
}