export function buildGroupGenerationPrompt(
  prefs: GroupPreferences,
  signatures: GroupSignature[]
): string {
  const signatureBlock = signatures.length > 0
    ? `### ПАМЯТЬ РАЗНООБРАЗИЯ\nНедавние ансамбли уже использовали эти сочетания. Не копируй их буквально; выбери другой угол, среду, социальные роли или рисунок знаний:\n${signatures
        .map((item) => `- среда: ${item.setting}; тон: ${item.tone}; роли: ${item.roles.join(", ")}; связи: ${item.relationPattern}; позиция игрока: ${item.playerAnchor ?? "не задана"}; знания: ${item.informationPattern ?? "не задано"}`)
        .join("\n")}`
    : "";

  return [
    `### РОЛЬ\nТы — опытный нарративный дизайнер и редактор современных групповых ролевых сцен на русском языке. Твоя задача — придумать ансамбль взаимосвязанных, но автономных взрослых персонажей, конкретное место, социальную физику, общий момент и вход для игрока.`,
    `### ЗАДАЧА\nСгенерируй ровно ${prefs.size} персонажа(ей) одной современной реалистичной сцены. Результат будет сразу превращён в групповую ветку: карточки сохранятся в библиотеке, relations попадут в состояние сцены, а opening станет первым сообщением.`,
    `### ПРЕДПОЧТЕНИЯ\n${resolveGroupPreferencesBlock(prefs)}`,
    PRINCIPLES.replace("${size}", String(prefs.size)),
    signatureBlock,
    `### ФОРМАТ\nВерни только один валидный JSON-объект без markdown, комментариев и текста до/после него. Сохрани ключи exactly как в схеме. В cast должно быть ровно ${prefs.size} элементов; в relations — минимум ${Math.max(1, prefs.size - 1)} направленных связей. Версия blueprint — 2. Если взрослый профиль выключен, chemistry должен быть пустым массивом.`,
    SCHEMA,
    SELF_CHECK,
    "Сначала продумай ансамбль внутренне, затем верни только JSON. Не добавляй поля с рассуждениями.",
  ].filter(Boolean).join("\n\n");
}

