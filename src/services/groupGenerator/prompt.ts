export function buildGroupGenerationPrompt(
  prefs: GroupPreferences,
  signatures: GroupSignature[]
): string {
  const signatureBlock = signatures.length > 0
    ? `### ПАМЯТЬ РАЗНООБРАЗИЯ\nНедавние ансамбли уже использовали эти сочетания. Не копируй их буквально; выбери другой угол, среду или набор ролей:\n${signatures
        .map((item) => `- среда: ${item.setting}; тон: ${item.tone}; роли: ${item.roles.join(", ")}; связи: ${item.relationPattern}`)
        .join("\n")}`
    : "";

  return [
    `### РОЛЬ\nТы — опытный нарративный дизайнер и редактор групповых ролевых сцен на русском языке. Твоя задача — придумать ансамбль взаимосвязанных, но автономных взрослых персонажей, общий момент сцены и вход для игрока.`,
    `### ЗАДАЧА\nСгенерируй ровно ${prefs.size} персонажа(ей) одной сцены. Результат будет сразу превращён в групповую ветку: карточки сохранятся в библиотеке, relations попадут в состояние сцены, а opening станет первым сообщением.`,
    `### ПРЕДПОЧТЕНИЯ\n${resolveGroupPreferencesBlock(prefs)}`,
    PRINCIPLES.replace("${size}", String(prefs.size)),
    signatureBlock,
    `### ФОРМАТ\nВерни только один валидный JSON-объект без markdown, комментариев и текста до/после него. Сохрани ключи exactly как в схеме. В cast должно быть ровно ${prefs.size} элементов; в relations — минимум ${Math.max(1, prefs.size - 1)} направленных связей.`,
    SCHEMA,
    SELF_CHECK,
    "Сначала продумай ансамбль внутренне, затем верни только JSON. Не добавляй поля с рассуждениями.",
  ].filter(Boolean).join("\n\n");
}

export function buildGroupCorrectionPrompt(
  original: string,
  brokenOutput: string,
  issues: string[]
): string {
  return `${original}

### КОРРЕКЦИОННЫЙ ПОВТОР
Предыдущий JSON не прошёл строгую проверку. Исправь все проблемы:
${issues.slice(0, 18).map((issue) => `- ${issue}`).join("\n")}

Предыдущий ответ:
${brokenOutput.slice(0, 18000)}

Верни полный исправленный JSON по той же схеме. Не сокращай cast и relations, не добавляй пояснений.`;
}

const SECTION_HINTS: Record<GroupRegenerationSection, string> = {
  scene: "Перепиши только scene: место, завязку, текущий момент, тон и hook; cast и relations должны остаться теми же.",
  opening: "Перепиши только opening: общий живой вход в текущую сцену; не меняй scene, cast и relations.",
  relations: "Перепиши только relations: направленные взаимные связи между теми же героями; не меняй cast, scene и opening.",
  cast: "Перепиши cast как ансамбль тех же ролей и размера, сохранив scene и relations настолько, чтобы ключи остались совместимыми; не меняй opening без необходимости.",
};

export function buildGroupPartialPrompt(
  prefs: GroupPreferences,
  blueprint: GroupBlueprint,
  section: GroupRegenerationSection,
  extraInstruction = ""
): string {
  return `### ЧАСТИЧНАЯ ПЕРЕГЕНЕРАЦИЯ ГРУППЫ
Ты — редактор уже существующей групповой сцены. ${SECTION_HINTS[section]}

### ОГРАНИЧЕНИЯ
- Состав: ровно ${prefs.size} взрослых персонажа(ей); не меняй количество.
- Игрок не обязан быть центром внимания и не получает навязанных мыслей/действий.
- Не добавляй обязательную романтику, трагедию или сексуальный контекст.
- ${extraInstruction || "Сохрани внутреннюю логику ансамбля и различимость голосов."}

### ТЕКУЩИЙ BLUEPRINT
${JSON.stringify(blueprint).slice(0, 24000)}

### ПРЕДПОЧТЕНИЯ КОНТЕКСТА
${resolveGroupPreferencesBlock(prefs)}

${SECTION_HINTS[section]}

Верни полный JSON той же структуры одним объектом, даже если изменяется только одна секция. Поля, не относящиеся к выбранной секции, скопируй без смысловых изменений.`;
}

export function groupSchemaText(): string {
  return SCHEMA;
}

export function selectedGroupOptionNames(selections: Record<string, string[]>): string[] {
  const names: string[] = [];
  for (const category of Object.values(selections)) {
    names.push(...category);
  }
  return names;
}
