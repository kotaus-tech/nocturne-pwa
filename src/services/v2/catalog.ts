/** Быстрый доступ к категории по id. */
export function getCategory(id: string): V2Category | undefined {
  return V2_CATALOG.find((category) => category.id === id);
}

/** Опция по id в любой категории. */
export function findOption(optionId: string): { category: V2Category; option: V2Option } | null {
  for (const category of V2_CATALOG) {
    const option = category.options.find((item) => item.id === optionId);
    if (option) return { category, option };
  }
  return null;
}

